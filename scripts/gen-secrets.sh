#!/bin/sh
# gen-secrets.sh — generate a unique shared/secrets.env for this player.
#
# Every player should run this once so their lab has its own credentials,
# session token, and flags. The flags are random, so no two players share a
# flag value (each solve is unique to that player's instance). The TLS private
# key for level 2 is already regenerated on every container boot by the
# vulnerable server, so it needs nothing here.
#
# By design this does NOT hide the secrets from you: secrets.env lives on your
# own machine and you can read it. The lab is an honour-system learning
# exercise — the intended path is the Heartbleed exploit, not `cat`. See
# docs/how-to-run.md.
#
# Usage:
#   scripts/gen-secrets.sh            # create secrets.env (refuses to overwrite)
#   scripts/gen-secrets.sh --force    # regenerate, replacing the existing file
#
# POSIX sh, no dependencies beyond coreutils (/dev/urandom + od).
set -eu

ROOT=$(cd "$(dirname "$0")/.." && pwd)
OUT="$ROOT/shared/secrets.env"

FORCE=0
case "${1:-}" in
  --force|-f) FORCE=1 ;;
  '') ;;
  *) printf 'usage: %s [--force]\n' "$0" >&2; exit 2 ;;
esac

if [ -e "$OUT" ] && [ "$FORCE" -ne 1 ]; then
  printf 'secrets.env already exists at %s\n' "$OUT" >&2
  printf 'Keeping it (your flags would change if regenerated). Use --force to replace.\n' >&2
  exit 0
fi

# Hex-encode N random bytes (2N hex chars). Portable: no openssl required.
rand() { head -c "$1" /dev/urandom | od -An -tx1 | tr -d ' \n'; }

mkdir -p "$ROOT/shared"

# Write atomically so a failure never leaves a half-written secrets.env that
# would wedge the vulnerable server's `: "${LAB_FLAG_L2:?...}"` guards.
tmp="$OUT.tmp.$$"
{
  printf '# Unique per-player lab secrets (FAKE values, memory only).\n'
  printf '# Generated by scripts/gen-secrets.sh — re-run with --force to rotate.\n'
  printf 'LAB_USER=admin\n'
  printf 'LAB_PASS=S3cr3t-%s\n'        "$(rand 4)"
  printf 'LAB_TOKEN=%s\n'              "$(rand 16)"
  printf 'LAB_FLAG=CTF_FLAG{creds-%s}\n'     "$(rand 6)"
  printf 'LAB_FLAG_L2=CTF_FLAG{privkey-%s}\n' "$(rand 6)"
  printf 'LAB_FLAG_L3=CTF_FLAG{session-%s}\n' "$(rand 6)"
} > "$tmp"
mv "$tmp" "$OUT"

printf 'Wrote unique secrets to %s\n' "$OUT"
printf 'Keys: %s\n' "$(grep -oE '^[A-Z_0-9]+=' "$OUT" | tr -d '=' | tr '\n' ' ')"
printf 'The real flags are in that file — the challenge is to leak them, not read them.\n'
